//! 所属模块：core / 数据模型 / 采样音色库
//! 文件用途：
//! - 定义内置采样音色库的清单结构（乐器、分区、音域与力度层）。
//! - 提供按 id 查询乐器、按文件路径查询内嵌音频字节的只读接口。
//! - 音色数据来自 SoundBug SoundSampler3，运行时归入 SurfingStudio。
//!
//! 函数清单：
//! - `BankZone::matches`：判断分区是否覆盖指定音高与力度。
//! - `SampleSettings` 的 `Default`：采样乐器通用默认参数。
//! - `SampleInstrument::new`：按音色 id 构造乐器引用。
//! - `instruments` / `instrument` / `sample_bytes`：清单与音频数据查询。
//!
//! Module: core / data model / sampled sound bank
//! Purpose:
//! - Define the manifest structures for the built-in sampled instrument bank (instruments,
//!   zones, ranges and velocity layers).
//! - Provide read-only lookups by instrument id and by embedded audio file path.
//! - The audio content originates from SoundBug SoundSampler3 and is presented as SurfingStudio.
//!
//! Functions:
//! - `BankZone::matches`: whether a zone covers the given pitch and velocity.
//! - `Default` for `SampleSettings`: shared defaults for sampled instruments.
//! - `SampleInstrument::new`: build an instrument reference from a bank id.
//! - `instruments` / `instrument` / `sample_bytes`: manifest and audio lookups.

use serde::{Deserialize, Serialize};
use std::collections::HashMap;
use std::sync::OnceLock;

/// 清单 JSON 在编译期内嵌，随可执行文件发布。
/// The manifest JSON is embedded at build time and shipped with the executable.
const MANIFEST_JSON: &str = include_str!("../../../assets/soundbank/manifest.json");

// 由 build.rs 生成的 `FILES`：文件名 → 内嵌音频字节。
// `FILES` is generated by build.rs: file name → embedded audio bytes.
include!(concat!(env!("OUT_DIR"), "/soundbank_assets.rs"));

/// 一个采样分区：音频文件、根音、键位范围与力度范围。
/// One sample zone: audio file, root note, key range and velocity range.
#[derive(Clone, Debug, Deserialize)]
pub struct BankZone {
    pub file: String,
    pub root: u8,
    pub lo: u8,
    pub hi: u8,
    pub lo_vel: u8,
    pub hi_vel: u8,
}

impl BankZone {
    /// 所属模块：core / 数据模型 / 采样音色库
    /// 功能：判断该分区是否覆盖指定音高与力度。
    /// 输入：`pitch` MIDI 音高（0~127）、`velocity` 力度（1~127）。
    /// 输出/副作用：返回布尔值；不修改状态。
    /// 复杂度：时间 O(1)，空间 O(1)。
    ///
    /// Module: core / data model / sampled sound bank
    /// Purpose: Whether this zone covers the given pitch and velocity.
    /// Inputs: `pitch` MIDI note (0..=127), `velocity` note-on velocity (1..=127).
    /// Outputs / side effects: the boolean; no state change.
    /// Complexity: O(1) time and space.
    pub fn matches(&self, pitch: u8, velocity: u8) -> bool {
        pitch >= self.lo && pitch <= self.hi && velocity >= self.lo_vel && velocity <= self.hi_vel
    }
}

/// 音色库中的一件乐器（静态清单）。
/// One instrument in the static bank manifest.
#[derive(Clone, Debug, Deserialize)]
pub struct BankInstrument {
    pub id: String,
    pub name: String,
    pub category: String,
    pub range: [u8; 2],
    pub sample_rate: u32,
    #[serde(rename = "loop", default)]
    pub looped: bool,
    pub zones: Vec<BankZone>,
}

/// 采样乐器的可调参数（音量、音色、包络与力度跟随）。
/// Adjustable parameters for a sampled instrument (level, tone, envelope and velocity response).
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct SampleSettings {
    pub level: f32,
    /// 0 = 最暗，1 = 原始亮度；通过一阶低通实现。
    /// 0 = darkest, 1 = original brightness; implemented with a one-pole low-pass.
    pub tone: f32,
    pub attack: f32,
    pub release: f32,
    /// 力度对音量的影响程度（0 = 固定音量，1 = 完全跟随）。
    /// How strongly velocity affects level (0 = fixed, 1 = full).
    pub velocity: f32,
}

impl Default for SampleSettings {
    fn default() -> Self {
        Self {
            level: 0.85,
            tone: 1.0,
            attack: 0.002,
            release: 0.28,
            velocity: 0.7,
        }
    }
}

/// 采样乐器引用：只保存音色 id 与参数，工程文件不会重复清单内容。
/// Sampled instrument reference: stores only the bank id and settings so projects stay small.
#[derive(Clone, Debug, PartialEq, Serialize)]
pub struct SampleInstrument {
    pub bank: String,
    #[serde(default)]
    pub name: String,
    #[serde(default)]
    pub settings: SampleSettings,
}

impl<'de> Deserialize<'de> for SampleInstrument {
    /// 所属模块：core / 数据模型 / 采样音色库
    /// 功能：兼容当前 `[bank, name, settings]` 与旧版 `[bank, name, level, attack, release]` 编码。
    /// 输入：反序列化器。
    /// 输出/副作用：返回采样乐器引用；字段不足时返回错误。
    /// 复杂度：时间 O(字段数)，空间 O(1)。
    ///
    /// Module: core / data model / sampled sound bank
    /// Purpose: Accept both the current `[bank, name, settings]` encoding and the legacy
    /// `[bank, name, level, attack, release]` layout.
    /// Inputs: deserializer.
    /// Outputs / side effects: the instrument reference; errors on missing fields.
    /// Complexity: O(fields) time and O(1) space.
    fn deserialize<D>(deserializer: D) -> Result<Self, D::Error>
    where
        D: serde::Deserializer<'de>,
    {
        struct SampleVisitor;

        impl<'de> serde::de::Visitor<'de> for SampleVisitor {
            type Value = SampleInstrument;

            fn expecting(&self, formatter: &mut std::fmt::Formatter) -> std::fmt::Result {
                formatter.write_str("采样乐器引用 / sampled instrument reference")
            }

            fn visit_seq<A>(self, mut seq: A) -> Result<Self::Value, A::Error>
            where
                A: serde::de::SeqAccess<'de>,
            {
                let bank: String = seq
                    .next_element()?
                    .ok_or_else(|| serde::de::Error::missing_field("bank"))?;
                let name: String = seq.next_element()?.unwrap_or_default();
                let third: serde_json::Value = seq
                    .next_element()?
                    .ok_or_else(|| serde::de::Error::missing_field("settings"))?;
                if third.is_array() || third.is_object() {
                    let settings: SampleSettings = serde_json::from_value(third)
                        .map_err(|error| serde::de::Error::custom(error.to_string()))?;
                    return Ok(SampleInstrument {
                        bank,
                        name,
                        settings,
                    });
                }
                let level = third
                    .as_f64()
                    .ok_or_else(|| serde::de::Error::custom("level 不是数字"))?
                    as f32;
                let attack: f32 = seq
                    .next_element()?
                    .ok_or_else(|| serde::de::Error::missing_field("attack"))?;
                let release: f32 = seq
                    .next_element()?
                    .ok_or_else(|| serde::de::Error::missing_field("release"))?;
                Ok(SampleInstrument {
                    bank,
                    name,
                    settings: SampleSettings {
                        level,
                        attack,
                        release,
                        ..SampleSettings::default()
                    },
                })
            }

            fn visit_map<A>(self, mut map: A) -> Result<Self::Value, A::Error>
            where
                A: serde::de::MapAccess<'de>,
            {
                let mut bank = None;
                let mut name = String::new();
                let mut settings = None;
                let mut level = None;
                let mut attack = None;
                let mut release = None;
                while let Some(key) = map.next_key::<String>()? {
                    match key.as_str() {
                        "bank" => bank = Some(map.next_value()?),
                        "name" => name = map.next_value()?,
                        "settings" => settings = Some(map.next_value()?),
                        "level" => level = Some(map.next_value()?),
                        "attack" => attack = Some(map.next_value()?),
                        "release" => release = Some(map.next_value()?),
                        _ => {
                            let _: serde::de::IgnoredAny = map.next_value()?;
                        }
                    }
                }
                let bank = bank.ok_or_else(|| serde::de::Error::missing_field("bank"))?;
                let settings = match settings {
                    Some(settings) => settings,
                    None => SampleSettings {
                        level: level.unwrap_or(SampleSettings::default().level),
                        attack: attack.unwrap_or(SampleSettings::default().attack),
                        release: release.unwrap_or(SampleSettings::default().release),
                        ..SampleSettings::default()
                    },
                };
                Ok(SampleInstrument {
                    bank,
                    name,
                    settings,
                })
            }
        }

        deserializer.deserialize_any(SampleVisitor)
    }
}

impl SampleInstrument {
    /// 所属模块：core / 数据模型 / 采样音色库
    /// 功能：按音色 id 创建引用，并填入清单中的显示名。
    /// 输入：`id` 音色库 id。
    /// 输出/副作用：返回乐器引用；未知 id 时名称回退为 id。
    /// 复杂度：时间 O(清单大小)，空间 O(1)。
    ///
    /// Module: core / data model / sampled sound bank
    /// Purpose: Create a reference for a bank id and fill in its display name.
    /// Inputs: `id` bank instrument id.
    /// Outputs / side effects: the reference; unknown ids fall back to the id as name.
    /// Complexity: O(manifest size) time and O(1) space.
    pub fn new(id: &str) -> Self {
        let name = instrument(id)
            .map(|entry| entry.name.clone())
            .unwrap_or_else(|| id.to_string());
        Self {
            bank: id.to_string(),
            name,
            settings: SampleSettings::default(),
        }
    }

    /// 所属模块：core / 数据模型 / 采样音色库
    /// 功能：返回该引用对应的静态清单乐器。
    /// 输入：`self`。
    /// 输出/副作用：清单条目的引用；未知 id 返回 `None`。
    /// 复杂度：时间 O(清单大小)，空间 O(1)。
    ///
    /// Module: core / data model / sampled sound bank
    /// Purpose: Resolve the static manifest entry for this reference.
    /// Inputs: `self`.
    /// Outputs / side effects: the manifest entry, or `None` for unknown ids.
    /// Complexity: O(manifest size) time and O(1) space.
    pub fn entry(&self) -> Option<&'static BankInstrument> {
        instrument(&self.bank)
    }
}

#[derive(Deserialize)]
struct Manifest {
    instruments: Vec<BankInstrument>,
}

static MANIFEST: OnceLock<Vec<BankInstrument>> = OnceLock::new();
static INDEX: OnceLock<HashMap<&'static str, usize>> = OnceLock::new();

/// 所属模块：core / 数据模型 / 采样音色库
/// 功能：返回音色库全部乐器（首次调用时解析内嵌清单）。
/// 输入：无。
/// 输出/副作用：静态切片；解析失败时为空。
/// 复杂度：首次 O(清单解析)，之后 O(1)。
///
/// Module: core / data model / sampled sound bank
/// Purpose: Return every bank instrument (the embedded manifest is parsed on first use).
/// Inputs: none.
/// Outputs / side effects: a static slice; empty when parsing fails.
/// Complexity: O(manifest parse) on first use, O(1) afterwards.
pub fn instruments() -> &'static [BankInstrument] {
    MANIFEST
        .get_or_init(|| {
            serde_json::from_str::<Manifest>(MANIFEST_JSON)
                .map(|manifest| manifest.instruments)
                .unwrap_or_default()
        })
        .as_slice()
}

/// 所属模块：core / 数据模型 / 采样音色库
/// 功能：按 id 查询音色库乐器。
/// 输入：`id` 音色 id。
/// 输出/副作用：清单条目引用；不存在时返回 `None`。
/// 复杂度：时间 O(1)，空间 O(1)。
///
/// Module: core / data model / sampled sound bank
/// Purpose: Look up a bank instrument by id.
/// Inputs: `id` instrument id.
/// Outputs / side effects: the manifest entry, or `None`.
/// Complexity: O(1) time and space.
pub fn instrument(id: &str) -> Option<&'static BankInstrument> {
    let index = INDEX.get_or_init(|| {
        instruments()
            .iter()
            .enumerate()
            .map(|(index, entry)| (entry.id.as_str(), index))
            .collect()
    });
    index.get(id).map(|index| &instruments()[*index])
}

/// 所属模块：core / 数据模型 / 采样音色库
/// 功能：按相对路径查询内嵌音频字节。
/// 输入：`file` 清单中的相对路径（如 `GrandPiano/zone_000.ogg`）。
/// 输出/副作用：静态字节切片；不存在时返回 `None`。
/// 复杂度：时间 O(文件数)，空间 O(1)。
///
/// Module: core / data model / sampled sound bank
/// Purpose: Look up embedded audio bytes by relative path.
/// Inputs: `file` relative path from the manifest (e.g. `GrandPiano/zone_000.ogg`).
/// Outputs / side effects: the static byte slice, or `None`.
/// Complexity: O(file count) time and O(1) space.
pub fn sample_bytes(file: &str) -> Option<&'static [u8]> {
    FILES
        .iter()
        .find(|(name, _)| *name == file)
        .map(|(_, bytes)| *bytes)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// 覆盖：内嵌清单可解析，且每个分区都能找到对应音频数据。
    /// Covers: the embedded manifest parses and every zone resolves to embedded audio bytes.
    #[test]
    fn manifest_and_audio_are_embedded() {
        let entries = instruments();
        assert_eq!(entries.len(), 128, "采样音色库应包含 128 件乐器");
        let mut zones = 0;
        for entry in entries {
            assert!(!entry.zones.is_empty(), "{} 缺少分区", entry.id);
            for zone in &entry.zones {
                assert!(
                    sample_bytes(&zone.file).is_some(),
                    "{} 的 {} 未内嵌",
                    entry.id,
                    zone.file
                );
                zones += 1;
            }
        }
        assert!(zones >= 384, "采样分区数量异常：{zones}");
    }

    /// 覆盖：按 id 查询与未知 id 的回退名称。
    /// Covers: lookup by id and the fallback name for unknown ids.
    #[test]
    fn instrument_lookup_and_fallback_name() {
        let entry = instrument("GrandPiano").expect("GrandPiano");
        assert_eq!(entry.name, "大钢琴");
        let missing = SampleInstrument::new("missing");
        assert_eq!(missing.name, "missing");
        assert!(missing.entry().is_none());
    }

    /// 覆盖：清单音域内每个音高在低/高力度下都有分区覆盖。
    /// Covers: every pitch in the declared range has a zone for both velocity extremes.
    #[test]
    fn manifest_covers_every_declared_pitch() {
        for entry in instruments() {
            for pitch in entry.range[0]..=entry.range[1] {
                assert!(
                    entry.zones.iter().any(|zone| zone.matches(pitch, 1)),
                    "{} 缺少音高 {pitch} 的低力度分区",
                    entry.id
                );
                assert!(
                    entry.zones.iter().any(|zone| zone.matches(pitch, 127)),
                    "{} 缺少音高 {pitch} 的高力度分区",
                    entry.id
                );
            }
        }
    }

    /// 覆盖：当前与旧版 `Sampled` 编码均可反序列化。
    /// Covers: both the current and legacy `Sampled` encodings deserialize.
    #[test]
    fn sample_instrument_accepts_legacy_layout() {
        let current = SampleInstrument::new("Violin");
        let bytes = rmp_serde::to_vec(&current).expect("encode current");
        let decoded: SampleInstrument = rmp_serde::from_slice(&bytes).expect("decode current");
        assert_eq!(decoded, current);

        #[derive(serde::Serialize)]
        struct Legacy {
            bank: String,
            name: String,
            level: f32,
            attack: f32,
            release: f32,
        }
        let legacy = Legacy {
            bank: "Violin".into(),
            name: "小提琴".into(),
            level: 0.8,
            attack: 0.002,
            release: 0.35,
        };
        let bytes = rmp_serde::to_vec(&legacy).expect("encode legacy");
        let decoded: SampleInstrument = rmp_serde::from_slice(&bytes).expect("decode legacy");
        assert_eq!(decoded.bank, "Violin");
        assert_eq!(decoded.name, "小提琴");
        assert!((decoded.settings.level - 0.8).abs() < 1e-6);
        assert!((decoded.settings.release - 0.35).abs() < 1e-6);
    }

    /// 覆盖：旧工程中的 `Sampled` 变体可映射到新的 `Sample` 变体。
    /// Covers: the legacy `Sampled` variant maps to the new `Sample` variant.
    #[test]
    fn legacy_sampled_variant_loads_as_sample() {
        #[derive(serde::Serialize)]
        struct LegacySample {
            bank: String,
            name: String,
            level: f32,
            attack: f32,
            release: f32,
        }
        #[derive(serde::Serialize)]
        enum LegacyInstrument {
            Sampled(LegacySample),
        }
        let legacy = LegacyInstrument::Sampled(LegacySample {
            bank: "Violin".into(),
            name: "小提琴".into(),
            level: 0.8,
            attack: 0.002,
            release: 0.35,
        });
        let bytes = rmp_serde::to_vec(&legacy).expect("encode legacy instrument");
        let decoded: crate::core::model::InstrumentRef =
            rmp_serde::from_slice(&bytes).expect("decode legacy instrument");
        match decoded {
            crate::core::model::InstrumentRef::Sample(sample) => {
                assert_eq!(sample.bank, "Violin");
                assert_eq!(sample.name, "小提琴");
            }
            other => panic!("expected Sample, got {other:?}"),
        }
    }

    /// 覆盖：分区按音高与力度匹配。
    /// Covers: zone matching by pitch and velocity.
    #[test]
    fn zones_match_key_and_velocity_ranges() {
        let zone = BankZone {
            file: "GrandPiano/zone_000.wav".into(),
            root: 29,
            lo: 21,
            hi: 32,
            lo_vel: 1,
            hi_vel: 63,
        };
        assert!(zone.matches(21, 1));
        assert!(zone.matches(32, 63));
        assert!(!zone.matches(33, 63));
        assert!(!zone.matches(21, 64));
    }
}
