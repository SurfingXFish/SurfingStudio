//! 所属模块：构建脚本 / 资源内嵌
//! 文件用途：
//! - 把 `assets/icon.ico` 编译成资源并链接进 `surfing-studio.exe`，让资源管理器/任务栏显示新图标。
//! - 扫描 `assets/soundbank` 并生成内嵌音频文件表，供采样音色库在运行时零文件依赖地读取。
//! - 找不到资源编译器时只发出警告，不影响其它平台与普通构建。
//!
//! Module: build script / resource embedding
//! Purpose:
//! - Compile `assets/icon.ico` and link it into `surfing-studio.exe` so Explorer and the taskbar
//!   show the new icon.
//! - Scan `assets/soundbank` and generate an embedded audio table so the sampled instrument bank
//!   has no runtime file dependency.
//! - Only warn when no resource compiler is available; other platforms and plain builds are
//!   unaffected.

use std::path::{Path, PathBuf};
use std::process::Command;

fn main() {
    println!("cargo:rerun-if-changed=assets/icon.ico");
    embed_soundbank();
    #[cfg(windows)]
    embed_icon();
}

/// 所属模块：构建脚本 / 采样音色库
/// 功能：递归扫描 `assets/soundbank` 的音频文件并生成 `soundbank_assets.rs`。
/// 输入：无（读取 `CARGO_MANIFEST_DIR` 与 `OUT_DIR`）。
/// 输出/副作用：写入 `$OUT_DIR/soundbank_assets.rs`，其中 `FILES` 为「相对路径 → 内嵌字节」表；
/// 目录不存在时写入空表。
/// 复杂度：时间 O(文件数)，空间 O(生成源码大小)。
///
/// Module: build script / sampled sound bank
/// Purpose: Recursively scan audio files under `assets/soundbank` and generate
/// `soundbank_assets.rs`.
/// Inputs: none (reads `CARGO_MANIFEST_DIR` and `OUT_DIR`).
/// Outputs / side effects: writes `$OUT_DIR/soundbank_assets.rs` whose `FILES` maps relative paths
/// to embedded bytes; writes an empty table when the directory is missing.
/// Complexity: O(file count) time and O(generated source size) space.
fn embed_soundbank() {
    println!("cargo:rerun-if-changed=assets/soundbank");
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("manifest dir"));
    let root = manifest.join("assets").join("soundbank");
    let out = PathBuf::from(std::env::var("OUT_DIR").expect("out dir"));
    let mut files = Vec::new();
    collect_audio(&root, &root, &mut files);
    files.sort();

    let mut source =
        String::from("// Generated by build.rs: embedded sampled-instrument audio files.\n");
    source.push_str("pub static FILES: &[(&str, &[u8])] = &[\n");
    for (relative, absolute) in files {
        let absolute = absolute.to_string_lossy().replace('\\', "/");
        source.push_str(&format!(
            "    (r#\"{relative}\"#, include_bytes!(r#\"{absolute}\"#)),\n"
        ));
    }
    source.push_str("];\n");
    if let Err(error) = std::fs::write(out.join("soundbank_assets.rs"), source) {
        println!("cargo:warning=写入采样音色库内嵌表失败：{error}");
    }
}

/// 所属模块：构建脚本 / 采样音色库
/// 功能：递归收集 `directory` 下的音频文件，并记录相对 `root` 的路径。
/// 输入：`root` 音色库根目录、`directory` 当前目录、`files` 输出列表。
/// 输出/副作用：向 `files` 追加 `(相对路径, 绝对路径)`；不修改文件。
/// 复杂度：时间 O(目录项数)，空间 O(音频文件数)。
///
/// Module: build script / sampled sound bank
/// Purpose: Recursively collect audio files under `directory`, recording paths relative to `root`.
/// Inputs: `root` bank root, `directory` current directory, `files` output list.
/// Outputs / side effects: appends `(relative, absolute)` pairs; no file changes.
/// Complexity: O(directory entries) time and O(audio file count) space.
fn collect_audio(root: &Path, directory: &Path, files: &mut Vec<(String, PathBuf)>) {
    let Ok(entries) = std::fs::read_dir(directory) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect_audio(root, &path, files);
        } else if path.extension().is_some_and(|extension| {
            extension.eq_ignore_ascii_case("wav")
                || extension.eq_ignore_ascii_case("ogg")
                || extension.eq_ignore_ascii_case("flac")
        }) {
            let Ok(relative) = path.strip_prefix(root) else {
                continue;
            };
            let relative = relative
                .components()
                .map(|component| component.as_os_str().to_string_lossy())
                .collect::<Vec<_>>()
                .join("/");
            files.push((relative, path));
        }
    }
}

/// 所属模块：构建脚本 / Windows 图标资源
/// 功能：用 rc.exe 或 windres 把图标资源链接到可执行文件。
/// 输入：无（读取 `CARGO_MANIFEST_DIR` 与 `OUT_DIR`）。
/// 输出/副作用：生成 `.res` / `.o` 并输出 `rustc-link-arg-bins`；失败时只打印警告。
/// 复杂度：时间 O(一次外部编译)，空间 O(1)。
///
/// Module: build script / Windows icon resource
/// Purpose: Link the icon resource through rc.exe or windres.
/// Inputs: none (reads `CARGO_MANIFEST_DIR` and `OUT_DIR`).
/// Outputs / side effects: writes `.res` / `.o` and emits `rustc-link-arg-bins`; only warns on
/// failure.
/// Complexity: O(one external compile) time and O(1) space.
#[cfg(windows)]
fn embed_icon() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("manifest dir"));
    let icon = manifest.join("assets").join("icon.ico");
    if !icon.exists() {
        println!("cargo:warning=assets/icon.ico 不存在，跳过 Windows 图标资源");
        return;
    }
    let out = PathBuf::from(std::env::var("OUT_DIR").expect("out dir"));
    let rc_file = out.join("app_icon.rc");
    let icon_text = icon.display().to_string().replace('\\', "\\\\");
    if std::fs::write(&rc_file, format!("IDI_ICON1 ICON \"{icon_text}\"\n")).is_err() {
        println!("cargo:warning=写入图标资源脚本失败，跳过 Windows 图标资源");
        return;
    }

    if let Some(rc) = find_rc() {
        let res = out.join("app_icon.res");
        let ok = Command::new(&rc)
            .arg("/nologo")
            .arg("/fo")
            .arg(&res)
            .arg(&rc_file)
            .status()
            .map(|status| status.success())
            .unwrap_or(false);
        if ok && res.exists() {
            println!("cargo:rustc-link-arg-bins={}", res.display());
            return;
        }
        println!("cargo:warning=rc.exe 运行失败，尝试 windres");
    }

    let obj = out.join("app_icon.o");
    let ok = Command::new("windres")
        .arg("-i")
        .arg(&rc_file)
        .arg("-o")
        .arg(&obj)
        .status()
        .map(|status| status.success())
        .unwrap_or(false);
    if ok && obj.exists() {
        println!("cargo:rustc-link-arg-bins={}", obj.display());
    } else {
        println!("cargo:warning=未找到 rc.exe / windres，可执行文件不会内嵌图标");
    }
}

/// 所属模块：构建脚本 / Windows 图标资源
/// 功能：定位 Windows SDK 的 rc.exe（取版本号最大的 x64 目录）。
/// 输入：无。
/// 输出/副作用：返回路径；找不到时返回 `None`。
/// 复杂度：时间 O(SDK 版本数)，空间 O(1)。
///
/// Module: build script / Windows icon resource
/// Purpose: Locate the Windows SDK rc.exe (highest version, x64).
/// Inputs: none.
/// Outputs / side effects: the path, or `None`.
/// Complexity: O(SDK versions) time and O(1) space.
#[cfg(windows)]
fn find_rc() -> Option<PathBuf> {
    if let Ok(program_files) = std::env::var("ProgramFiles(x86)") {
        let bin = Path::new(&program_files)
            .join("Windows Kits")
            .join("10")
            .join("bin");
        if let Ok(entries) = std::fs::read_dir(&bin) {
            let mut versions: Vec<PathBuf> = entries
                .filter_map(|entry| entry.ok().map(|entry| entry.path()))
                .filter(|path| path.is_dir())
                .collect();
            versions.sort();
            versions.reverse();
            for version in versions {
                let candidate = version.join("x64").join("rc.exe");
                if candidate.exists() {
                    return Some(candidate);
                }
            }
        }
    }
    Command::new("rc.exe")
        .arg("/?")
        .output()
        .ok()
        .filter(|output| output.status.success() || !output.stdout.is_empty())
        .map(|_| PathBuf::from("rc.exe"))
}
